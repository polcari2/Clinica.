-- =============================================================================
-- CLINICADENT - Script de inicialización de esquema Oracle para Producción (S13)
-- Alineado con las 12 entidades JPA reales de pe.edu.upeu.clinica
-- =============================================================================

-- Garantizar privilegios y cuota al usuario de aplicación (creado por APP_USER)
ALTER USER CLINICADENT_APP QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER, CREATE SEQUENCE TO CLINICADENT_APP;

-- 1. Módulo Catálogo y Tratamientos
CREATE TABLE CLINICADENT_APP.ESPECIALIDAD (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(200)
);

CREATE TABLE CLINICADENT_APP.PROCEDIMIENTOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ESPECIALIDAD NUMBER,
    NOMBRE VARCHAR2(100) NOT NULL UNIQUE,
    PRECIO NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_PROC_ESPECIALIDAD FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES CLINICADENT_APP.ESPECIALIDAD(ID),
    CONSTRAINT CK_PROC_PRECIO CHECK (PRECIO >= 0)
);

-- 2. Módulo Citas y Admisión
CREATE TABLE CLINICADENT_APP.PACIENTES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DNI VARCHAR2(15) NOT NULL UNIQUE,
    NOMBRES VARCHAR2(80) NOT NULL,
    APELLIDOS VARCHAR2(80) NOT NULL,
    TELEFONO VARCHAR2(20)
);

CREATE TABLE CLINICADENT_APP.CITAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PACIENTE NUMBER NOT NULL,
    FECHA_HORA TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_CITA_PACIENTE FOREIGN KEY (ID_PACIENTE) REFERENCES CLINICADENT_APP.PACIENTES(ID)
);

CREATE TABLE CLINICADENT_APP.DETALLE_CITAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CITA NUMBER NOT NULL,
    ID_PROCEDIMIENTO NUMBER,
    MOTIVO_CONSULTA VARCHAR2(255) NOT NULL,
    OBSERVACIONES VARCHAR2(500),
    CONSTRAINT FK_DET_CITA FOREIGN KEY (ID_CITA) REFERENCES CLINICADENT_APP.CITAS(ID),
    CONSTRAINT FK_DET_CITA_PROC FOREIGN KEY (ID_PROCEDIMIENTO) REFERENCES CLINICADENT_APP.PROCEDIMIENTOS(ID)
);

-- 3. Módulo Planes de Tratamiento
CREATE TABLE CLINICADENT_APP.TRATAMIENTOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PACIENTE NUMBER NOT NULL,
    FECHA_CREACION TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    COSTO_TOTAL NUMBER(10,2) NOT NULL,
    SALDO_PENDIENTE NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_TRAT_PACIENTE FOREIGN KEY (ID_PACIENTE) REFERENCES CLINICADENT_APP.PACIENTES(ID),
    CONSTRAINT CK_TRAT_COSTO CHECK (COSTO_TOTAL >= 0),
    CONSTRAINT CK_TRAT_SALDO CHECK (SALDO_PENDIENTE >= 0)
);

CREATE TABLE CLINICADENT_APP.DETALLE_TRATAMIENTO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TRATAMIENTO NUMBER NOT NULL,
    ID_PROCEDIMIENTO NUMBER NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    CANTIDAD NUMBER(10) NOT NULL,
    SUBTOTAL NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_DET_TRAT FOREIGN KEY (ID_TRATAMIENTO) REFERENCES CLINICADENT_APP.TRATAMIENTOS(ID),
    CONSTRAINT FK_DET_TRAT_PROC FOREIGN KEY (ID_PROCEDIMIENTO) REFERENCES CLINICADENT_APP.PROCEDIMIENTOS(ID),
    CONSTRAINT CK_DET_TRAT_CANT CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DET_TRAT_SUB CHECK (SUBTOTAL >= 0)
);

-- 4. Módulo Atenciones Clínicas
CREATE TABLE CLINICADENT_APP.ODONTOLOGOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COP VARCHAR2(20) NOT NULL UNIQUE,
    NOMBRES VARCHAR2(80) NOT NULL,
    APELLIDOS VARCHAR2(80) NOT NULL,
    ESPECIALIDAD VARCHAR2(100) NOT NULL
);

CREATE TABLE CLINICADENT_APP.ATENCIONES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CITA NUMBER NOT NULL,
    ID_ODONTOLOGO NUMBER NOT NULL,
    FA_ATENCION TIMESTAMP NOT NULL,
    DIAGNOSTICO VARCHAR2(500) NOT NULL,
    NOTA_MEDICA VARCHAR2(500),
    CONSTRAINT FK_ATEN_CITA FOREIGN KEY (ID_CITA) REFERENCES CLINICADENT_APP.CITAS(ID),
    CONSTRAINT FK_ATEN_ODONTOLOGO FOREIGN KEY (ID_ODONTOLOGO) REFERENCES CLINICADENT_APP.ODONTOLOGOS(ID)
);

CREATE TABLE CLINICADENT_APP.DETALLE_ATENCIONES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ATENCION NUMBER NOT NULL,
    ID_PROCEDIMIENTO NUMBER,
    PIEZA_DENTAL VARCHAR2(10) NOT NULL,
    INTERVENCION VARCHAR2(255) NOT NULL,
    OBSERVACION VARCHAR2(255),
    CONSTRAINT FK_DET_ATEN FOREIGN KEY (ID_ATENCION) REFERENCES CLINICADENT_APP.ATENCIONES(ID),
    CONSTRAINT FK_DET_ATEN_PROC FOREIGN KEY (ID_PROCEDIMIENTO) REFERENCES CLINICADENT_APP.PROCEDIMIENTOS(ID)
);

-- 5. Módulo Pagos y Caja
CREATE TABLE CLINICADENT_APP.METODO_PAGO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(150)
);

CREATE TABLE CLINICADENT_APP.PAGOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TRATAMIENTO NUMBER NOT NULL,
    FECHA_PAGO TIMESTAMP NOT NULL,
    MONTO_TOTAL NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_PAGO_TRATAMIENTO FOREIGN KEY (ID_TRATAMIENTO) REFERENCES CLINICADENT_APP.TRATAMIENTOS(ID),
    CONSTRAINT CK_PAGO_MONTO CHECK (MONTO_TOTAL >= 0)
);

CREATE TABLE CLINICADENT_APP.DETALLE_PAGOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PAGO NUMBER NOT NULL,
    ID_METODO_PAGO NUMBER NOT NULL,
    MONTO_ABONADO NUMBER(10,2) NOT NULL,
    NUMERO_OPERACION VARCHAR2(50),
    CONSTRAINT FK_DET_PAGO FOREIGN KEY (ID_PAGO) REFERENCES CLINICADENT_APP.PAGOS(ID),
    CONSTRAINT FK_DET_PAGO_METODO FOREIGN KEY (ID_METODO_PAGO) REFERENCES CLINICADENT_APP.METODO_PAGO(ID),
    CONSTRAINT CK_DET_PAGO_MONTO CHECK (MONTO_ABONADO > 0)
);

CREATE TABLE CLINICADENT_APP.DISTRIBUCION_PAGOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PAGO NUMBER NOT NULL,
    ID_TRATAMIENTO NUMBER NOT NULL,
    MONTO_APLICADO NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_DIST_PAGO FOREIGN KEY (ID_PAGO) REFERENCES CLINICADENT_APP.PAGOS(ID),
    CONSTRAINT FK_DIST_TRATAMIENTO FOREIGN KEY (ID_TRATAMIENTO) REFERENCES CLINICADENT_APP.TRATAMIENTOS(ID),
    CONSTRAINT CK_DIST_MONTO CHECK (MONTO_APLICADO > 0)
);

EXIT;

